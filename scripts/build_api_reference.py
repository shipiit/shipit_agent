"""Build docs/reference/api.md: every name `shipit_agent` exports, with its docstring.

    python scripts/build_api_reference.py

Names are grouped by the module that defines them, so related types sit together.
tests/test_api_reference.py fails when the page is out of date.
"""

from __future__ import annotations

import inspect
import sys
import typing
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "reference" / "api.md"

HEADER = """# Public API

Every name you can import from `shipit_agent`, grouped by the module that defines it,
with the first line of its docstring. Generated by `scripts/build_api_reference.py`
from `shipit_agent.__all__`, so nothing exported is missing.

```python
from shipit_agent import Agent, FunctionTool, PendingAction
```
"""


def _kind(obj: object) -> str:
    # Before classes: list[int] passes isclass on some Pythons, and a Union's own
    # class name differs between versions.
    if typing.get_origin(obj) is not None:
        return "type alias"
    if inspect.isclass(obj):
        return "class"
    if inspect.isfunction(obj) or inspect.isbuiltin(obj):
        return "function"
    return "constant"


def _summary(obj: object) -> str:
    if _kind(obj) == "type alias":
        return "A type alias."
    if _kind(obj) == "constant":
        type_name = "Path" if isinstance(obj, Path) else type(obj).__name__.lstrip("_")
        return f"A `{type_name}`."
    doc = inspect.getdoc(obj) or ""
    first = doc.strip().split("\n\n", 1)[0]
    return " ".join(first.split()) or "—"


def _module(name: str, obj: object) -> str:
    module = getattr(obj, "__module__", None) if _kind(obj) in ("class", "function") else None
    if not isinstance(module, str) or not module.startswith("shipit_agent"):
        return "shipit_agent"
    return ".".join(module.split(".")[:2])


def build() -> str:
    sys.path.insert(0, str(ROOT))
    import shipit_agent

    groups: dict[str, list[tuple[str, str, str]]] = {}
    for name in sorted(set(shipit_agent.__all__), key=lambda n: (n.lower(), n)):
        obj = getattr(shipit_agent, name)
        groups.setdefault(_module(name, obj), []).append((name, _kind(obj), _summary(obj)))
    parts = [HEADER]
    for module in sorted(groups):
        parts.append(f"\n## `{module}`\n\n| Name | Kind | What it is |\n|---|---|---|")
        for name, kind, summary in groups[module]:
            cell = summary.replace("|", "\\|")
            parts.append(f"| `{name}` | {kind} | {cell} |")
    return "\n".join(parts) + "\n"


if __name__ == "__main__":
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
